function escapePublicationText(value) {
    return String(value).replace(/[&<>"']/g, (c) => ({
        "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
    }[c]));
}

function renderPublications(target, { limit, tag, sort = "recent", query = "", year = "all" } = {}) {
    const el = document.getElementById(target);
    if (!el) return;
    let items = PUBLICATIONS.slice();
    if (tag && tag !== "all") items = items.filter((p) => p.tags.includes(tag));
    if (year !== "all") items = items.filter((p) => String(p.year) === year);
    const search = query.trim().toLocaleLowerCase();
    if (search) items = items.filter((p) => `${p.title} ${p.authors} ${p.venue}`.toLocaleLowerCase().includes(search));
    items.sort((a, b) => sort === "cited" ? (b.cited || 0) - (a.cited || 0) :
        sort === "oldest" ? (a.year || Infinity) - (b.year || Infinity) : (b.year || 0) - (a.year || 0));
    if (limit) items = items.slice(0, limit);
    el.innerHTML = items.length ? items.map((p) => `
        <article class="pub">
            <div class="year">${p.year || "Undated"}</div>
            <div><h3><a href="${escapePublicationText(p.link)}" target="_blank" rel="noopener">${escapePublicationText(p.title)} <span class="pub-arrow" aria-hidden="true">↗</span></a></h3>
            <div class="authors">${escapePublicationText(p.authors)}</div>
            <div class="venue">${escapePublicationText(p.venue)}</div></div>
        </article>`).join("") : '<div class="empty-state"><h3>No matching publications</h3><p>Try a different search, year, or topic.</p></div>';
    if (target === "pub-list") {
        document.getElementById("pub-count").textContent = `${items.length} publication${items.length === 1 ? "" : "s"}`;
    }
}

document.addEventListener("DOMContentLoaded", () => {
    if (!document.getElementById("pub-list")) return;
    const search = document.getElementById("pub-search");
    const year = document.getElementById("pub-year");
    const sort = document.getElementById("pub-sort");
    const years = [...new Set(PUBLICATIONS.map((p) => p.year).filter(Boolean))].sort((a, b) => b - a);
    for (const value of years) year.add(new Option(value, value));
    if (PUBLICATIONS.some((p) => !p.year)) year.add(new Option("Undated", "0"));
    let tag = "all";
    function update() { renderPublications("pub-list", { tag, query: search.value, year: year.value, sort: sort.value }); }
    const buttons = document.querySelectorAll("[data-filter]");
    buttons.forEach((button) => {
        button.setAttribute("aria-pressed", String(button.dataset.filter === tag));
        button.addEventListener("click", () => {
            tag = button.dataset.filter;
            buttons.forEach((b) => {
                b.classList.toggle("active", b === button);
                b.setAttribute("aria-pressed", String(b === button));
            });
            update();
        });
    });
    search.addEventListener("input", update);
    year.addEventListener("change", update);
    sort.addEventListener("change", update);
    update();
});
